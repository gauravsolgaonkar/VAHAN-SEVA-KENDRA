function hash(s) {
  let h = 2166136261;
  for (const c of s) h = Math.imul(h ^ c.charCodeAt(0), 16777619);
  return h >>> 0;
}

export function generateSample(regNo) {
  const h = hash(regNo);
  const pick = (arr, salt) => arr[(h >>> salt) % arr.length];
  const [maker, model, cat, catDesc, body, fuel, seats] = pick(MAKERS, 0);
  const transport = !['LMV', '2WN', 'AGRI', 'CEV'].includes(cat);
  const name = `${pick(FIRST, 3)} ${pick(FIRST, 7)} ${pick(LAST, 11)}`;
  const age = 1 + (h % 9);
  return {
    ...base,
    rc_number: regNo,
    registration_date: yearsAgo(age, h % 300),
    owner_name: name,
    father_name: `${name.split(' ')[1]} ${name.split(' ')[2]}`,
    present_address: `AT POST ${pick(['WAI', 'KARAD', 'BARAMATI', 'PHALTAN', 'INDAPUR'], 13)}, MAHARASHTRA`,
    permanent_address: `AT POST ${pick(['WAI', 'KARAD', 'BARAMATI', 'PHALTAN', 'INDAPUR'], 13)}, MAHARASHTRA`,
    vehicle_category: cat,
    vehicle_category_description: catDesc,
    vehicle_chasi_number: `MA${(h % 1e9).toString(36).toUpperCase().padStart(7, 'X')}${String(h).slice(-8)}`,
    vehicle_engine_number: `E${String(h * 7).slice(-10)}`,
    maker_description: maker,
    maker_model: model,
    body_type: body,
    fuel_type: fuel,
    color: pick(['WHITE', 'SILVER', 'RED', 'BLUE', 'GREY', 'BLACK'], 5),
    norms_type: age > 6 ? 'BHARAT STAGE IV' : 'BHARAT STAGE VI',
    fit_up_to: transport ? fromToday((h % 300) - 30) : fromToday(365 * (15 - age)),
    insurance_company: pick(INSURERS, 9),
    insurance_policy_number: `P${String(h).padStart(10, '0')}`,
    insurance_upto: fromToday((h % 200) - 20),
    manufacturing_date_formatted: `${new Date().getFullYear() - age}-0${1 + (h % 9)}`,
    registered_at: 'SATARA, Maharashtra',
    tax_upto: transport ? fromToday((h % 360) - 15) : 'LTT',
    tax_paid_upto: transport ? fromToday((h % 360) - 15) : 'LTT',
    seat_capacity: seats,
    vehicle_gross_weight: cat === 'MGV' ? '16200' : '',
    unladen_weight: cat === 'MGV' ? '5600' : '',
    pucc_number: `MH0110${String(h).slice(-10)}`,
    pucc_upto: fromToday((h % 170) - 10),
    permit_number: transport ? `MH11/P/${String(h).slice(-5)}` : '',
    permit_type: transport ? (cat === '3WT' ? 'Contract Carriage Permit' : 'Goods Permit') : null,
    permit_valid_upto: transport ? fromToday((h % 900) + 20) : null,
  };
}
